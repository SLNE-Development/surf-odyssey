package dev.slne.surf.odyssey.gradle.devstack

import org.gradle.api.DefaultTask
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.TaskAction
import java.io.File
import java.io.Serializable

/**
 * Writes a compose file that adds the microservices of the developmentStack extension to compose.yaml. Each one runs
 * its published image or is built from its Dockerfile, and is connected to the RabbitMQ, PostgreSQL and Valkey
 * services of compose.yaml. All share one database, and a one-shot service creates the schema of each and the
 * additional [schemas] before the [servers] start.
 */
abstract class GenerateMicroserviceCompose : DefaultTask() {
    @get:Input
    abstract val microservices: ListProperty<MicroserviceSpec>

    /** Schemas created besides those of the microservices. */
    @get:Input
    abstract val schemas: ListProperty<String>

    /** Compose services of compose.yaml that wait for the schemas. */
    @get:Input
    abstract val servers: ListProperty<String>

    @get:OutputFile
    abstract val composeFile: RegularFileProperty

    @TaskAction
    fun generate() {
        val specs = microservices.get()
        specs.forEach { spec ->
            require(SERVICE_NAME.matches(spec.name)) { "Microservice name '${spec.name}' is no valid compose service name" }
            if (spec.image == null) {
                require(spec.buildContext != null && spec.dockerfile != null) {
                    "Microservice '${spec.name}' needs an image or a build context and a Dockerfile"
                }
                require(File(spec.buildContext, spec.dockerfile).isFile) {
                    "Dockerfile of microservice '${spec.name}' not found at ${spec.buildContext}/${spec.dockerfile}"
                }
            }
        }
        val schemas = (specs.mapNotNull { it.schema } + schemas.get()).distinct()
        schemas.forEach { schema ->
            require(SCHEMA_NAME.matches(schema)) { "Schema name '$schema' may only contain a-z, 0-9 and _" }
        }

        val yaml = buildString {
            appendLine("# Generated by the generateDevelopmentMicroservices task from the developmentStack extension.")
            appendLine("# Changes are lost on the next start of the development stack.")
            appendLine()
            appendLine("services:")
            if (schemas.isNotEmpty()) {
                appendSchemaService(schemas)
                servers.get().forEach { appendSchemaDependency(it) }
            }
            specs.forEach { appendMicroservice(it) }
            // An override file without services is invalid
            if (specs.isEmpty() && schemas.isEmpty()) appendLine("  {}")
        }

        composeFile.get().asFile.apply { parentFile.mkdirs() }.writeText(yaml)
    }

    private fun StringBuilder.appendSchemaService(schemas: List<String>) {
        val script = "psql -v ON_ERROR_STOP=1 " +
                schemas.joinToString(" ") { schema -> "-c 'CREATE SCHEMA IF NOT EXISTS \"$schema\"'" }

        appendLine("  # Creates the schemas of the microservices in the shared database, then exits")
        appendLine("  $SCHEMA_SERVICE:")
        appendLine("    image: $POSTGRES_IMAGE")
        appendLine("    environment:")
        appendLine("      PGHOST: postgres")
        appendLine("      PGDATABASE: $DATABASE_NAME")
        appendLine("      PGUSER: \${POSTGRES_USERNAME:-surf}")
        appendLine("      PGPASSWORD: \${POSTGRES_PASSWORD:-surf}")
        appendLine("    command: [ \"sh\", \"-c\", ${quote(script)} ]")
        appendLine("    depends_on:")
        appendLine("      postgres:")
        appendLine("        condition: service_healthy")
        appendLine("    restart: \"no\"")
        appendLine()
    }

    private fun StringBuilder.appendSchemaDependency(service: String) {
        appendLine("  $service:")
        appendLine("    depends_on:")
        appendLine("      $SCHEMA_SERVICE:")
        appendLine("        condition: service_completed_successfully")
        appendLine()
    }

    private fun StringBuilder.appendMicroservice(spec: MicroserviceSpec) {
        appendLine("  ${spec.name}:")
        if (spec.image != null) {
            appendLine("    image: ${quote(spec.image)}")
            appendLine("    pull_policy: always")
        } else {
            appendLine("    build:")
            appendLine("      context: ${quote(spec.buildContext!!)}")
            appendLine("      dockerfile: ${quote(spec.dockerfile!!)}")
        }
        appendLine("    environment:")
        appendLine("      SURF_RABBITMQ_HOST: rabbitmq")
        appendLine("      SURF_RABBITMQ_PORT: 5672")
        appendLine("      SURF_RABBITMQ_USERNAME: \${RABBITMQ_USERNAME:-surf}")
        appendLine("      SURF_RABBITMQ_PASSWORD: \${RABBITMQ_PASSWORD:-surf}")
        appendLine("      SURF_RABBITMQ_VHOST: /")
        if (spec.schema != null) {
            appendLine("      SURF_DATABASE_TYPE: POSTGRESQL")
            appendLine("      SURF_DATABASE_HOST: postgres")
            appendLine("      SURF_DATABASE_PORT: 5432")
            appendLine("      SURF_DATABASE_NAME: $DATABASE_NAME")
            appendLine("      SURF_DATABASE_SCHEMA: ${spec.schema}")
            appendLine("      SURF_DATABASE_USERNAME: \${POSTGRES_USERNAME:-surf}")
            appendLine("      SURF_DATABASE_PASSWORD: \${POSTGRES_PASSWORD:-surf}")
        }
        if (spec.redis) {
            appendLine("      SURF_REDIS_HOST: valkey")
            appendLine("      SURF_REDIS_PORT: 6379")
            appendLine("      SURF_REDIS_PASSWORD: \${VALKEY_PASSWORD:-surf}")
        }
        appendLine("      JAVA_OPTS: ${quote(JAVA_OPTIONS)}")
        // Lets the microservice console be attached with "docker compose attach"
        appendLine("    stdin_open: true")
        appendLine("    tty: true")
        appendLine("    depends_on:")
        appendLine("      rabbitmq:")
        appendLine("        condition: service_healthy")
        if (spec.schema != null) {
            appendLine("      $SCHEMA_SERVICE:")
            appendLine("        condition: service_completed_successfully")
        }
        if (spec.redis) {
            appendLine("      valkey:")
            appendLine("        condition: service_healthy")
        }
        appendLine()
    }

    /** Quotes a YAML scalar. Dollar signs are doubled so compose does not interpolate them. */
    private fun quote(value: String) =
        "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "$$") + "\""

    /** A microservice of the generated compose file. */
    data class MicroserviceSpec(
        val name: String,
        val image: String?,
        /** Absolute path of the Docker build context. */
        val buildContext: String?,
        /** Path of the Dockerfile relative to [buildContext]. */
        val dockerfile: String?,
        val schema: String?,
        val redis: Boolean,
    ) : Serializable

    private companion object {
        const val SCHEMA_SERVICE = "postgres-schemas"
        const val DATABASE_NAME = "\${POSTGRES_DATABASE:-surf}"
        const val POSTGRES_IMAGE = "postgres:17.6-alpine"

        // Docker's default seccomp profile blocks io_uring, which Netty would otherwise pick for the RabbitMQ client.
        // surf-rabbitmq and surf-redis shade Netty and read relocated property names.
        const val JAVA_OPTIONS = "-Dio.netty.transport.noNative=true" +
                " -Ddev.slne.surf.rabbitmq.shaded.io.netty.transport.noNative=true" +
                " -Ddev.slne.surf.redis.shaded.io.netty.transport.noNative=true"

        val SERVICE_NAME = Regex("[a-z0-9][a-z0-9_-]*")
        val SCHEMA_NAME = Regex("[a-z0-9_]+")
    }
}
